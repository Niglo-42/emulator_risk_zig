pub const SYSCALL_UNSUPPORTED: u16 = 0xFFFF;

pub fn read_flags(flags: u16, regs: *[32]u32, ram_addr: u32) void {
    if (flags == 0xffff) {
        return;
    }
    for (10..16, 1..) |bit, i| {
        const shr: u4 = @truncate(bit);
        if ((flags >> shr) & 1 == 1) {
            regs[16 - i] += ram_addr;
        } // 0x4001
        // 0b0100_00.00_0000_0000
    }
}

